export function normalizeLocale(value) {
  if (value === 'zh' || /^zh[-_]/i.test(value || '')) return 'zh-CN';
  return value === 'en' ? 'en' : DEFAULT_LOCALE;
}

export function createTranslator(locale) {
  const normalized = normalizeLocale(locale);
  return (key, params = {}) => {
    if (MESSAGES[normalized][key] === undefined && process.env.NODE_ENV !== 'production') {
      console.warn(`Missing translation for "${key}" in ${normalized}; using English fallback`);
    }
    const template = MESSAGES[normalized][key] ?? MESSAGES.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
  };
}
